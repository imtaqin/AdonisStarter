/*
|--------------------------------------------------------------------------
| Imtaqin HTML -> Edge showcase pages
|--------------------------------------------------------------------------
|
| Regenerates resources/views/pages/showcase/*.edge from the vendor template in
| template/HTML/src/html. The output is disposable: edit this script, not the
| generated files. Re-run with:
|
|   node scripts/convert-showcase-pages.mjs
|
| Auth and error screens are skipped -- those are hand-written against real
| controllers in resources/views/pages/auth and pages/errors.
|
*/
import fs from 'node:fs'
import path from 'node:path'
import {
  REPLACED_PAGES,
  STANDALONE_PAGES,
  ensureJquery,
  matchClose,
  reindent,
  slugify,
  transformMarkup,
} from './theme_transform.mjs'

const ROOT = path.resolve(import.meta.dirname, '..')
const SRC = path.join(ROOT, 'template/HTML/src/html')
const OUT = path.join(ROOT, 'resources/views/pages/showcase')

const INCLUDE = /@SPK@include\("partials\/([a-z_-]+)\.html"(?:\s*,\s*([\s\S]*?))?\)/gi

/** Parses the loose object literal used by the template's include calls. */
function parseIncludeArgs(raw) {
  if (!raw) return {}
  const args = {}
  for (const m of raw.matchAll(/["']?(\w+)["']?\s*:\s*(["'])([\s\S]*?)\2/g)) {
    args[m[1]] = m[3].trim()
  }
  return args
}

function extract(html, file) {
  // --- head extras: anything the page adds between the shared head and </head>
  const mainhead = html.match(/@SPK@include\("partials\/mainhead\.html"\)/i)
  const headEnd = html.search(/<\/head>/i)
  let styles = ''
  if (mainhead && headEnd > -1) {
    styles = html.slice(mainhead.index + mainhead[0].length, headEnd)
  }

  // --- page header args
  let title = slugify(file).replace(/-/g, ' ')
  let subtitle = ''
  const ph = [...html.matchAll(INCLUDE)].find(
    (m) => m[1] === 'page-header' || m[1] === 'page_header'
  )
  const phMatch = html.match(
    /@SPK@include\("partials\/page-header\.html"\s*,\s*(\{[\s\S]*?\})\s*\)/i
  )
  if (phMatch) {
    const args = parseIncludeArgs(phMatch[1])
    if (args.title) title = args.title
    if (args.subtitle) subtitle = args.subtitle
  }

  // --- body content: inside .main-content > .container-fluid, minus the page header
  const mcIdx = html.search(/<div class="[^"]*\bmain-content\b[^"]*">/i)
  if (mcIdx === -1) throw new Error('no .main-content')
  const { close: mcClose } = matchClose(html, mcIdx, 'div')
  const mcInner = html.slice(html.indexOf('>', mcIdx) + 1, mcClose)

  const cfIdx = mcInner.search(/<div class="[^"]*\bcontainer-fluid\b[^"]*">/i)
  let content
  if (cfIdx === -1) {
    content = mcInner
  } else {
    const { close: cfClose } = matchClose(mcInner, cfIdx, 'div')
    content = mcInner.slice(mcInner.indexOf('>', cfIdx) + 1, cfClose)
  }
  // Keep the leading whitespace: reindent() needs the original indent of the
  // first line to compute the common prefix correctly.
  content = content.replace(INCLUDE, '')

  // --- page scripts: everything after the switcher script include, up to </body>
  const sw = html.match(/@SPK@include\("partials\/custom_switcherjs\.html"\)/i)
  const bodyEnd = html.search(/<\/body>/i)
  let scripts = ''
  if (sw && bodyEnd > -1) {
    scripts = html.slice(sw.index + sw[0].length, bodyEnd)
  }
  // custom.js is on every page, so the layout owns it
  scripts = scripts.replace(/<!--\s*Custom JS\s*-->\s*/gi, '')
  scripts = scripts.replace(/<script[^>]*\/theme\/js\/custom\.js[^>]*><\/script>/gi, '')
  scripts = scripts.replace(/<script[^>]*assets\/js\/custom\.js[^>]*><\/script>/gi, '')

  return { title, subtitle, styles, content, scripts, hadPageHeader: Boolean(ph || phMatch) }
}

function toEdge({ title, subtitle, styles, content, scripts }, file) {
  const q = (s) => s.replace(/'/g, "\\'")
  const props = [`title: '${q(title)}'`]
  if (subtitle) props.push(`subtitle: '${q(subtitle)}'`)

  const parts = [
    `{{--`,
    `  GENERATED by scripts/convert-showcase-pages.mjs from template/HTML/src/html/${file}`,
    `  Do not edit by hand -- re-running the script overwrites this file.`,
    `  This is reference markup for the Imtaqin theme, not application code.`,
    `--}}`,
    `@layouts.dashboard({ ${props.join(', ')} })`,
  ]

  if (styles.trim()) {
    parts.push(`  @slot('styles')`)
    parts.push(reindent(styles, '    '))
    parts.push(`  @end`)
    parts.push('')
  }

  parts.push(reindent(content, '  '))

  if (scripts.trim()) {
    parts.push('')
    parts.push(`  @slot('scripts')`)
    parts.push(reindent(scripts, '    '))
    parts.push(`  @end`)
  }

  parts.push(`@end`)
  return parts.join('\n') + '\n'
}

// ---------------------------------------------------------------------------

fs.rmSync(OUT, { recursive: true, force: true })
fs.mkdirSync(OUT, { recursive: true })

const files = fs
  .readdirSync(SRC)
  .filter((f) => f.endsWith('.html'))
  .sort()

const written = []
const skipped = []
const failed = []

for (const file of files) {
  const base = file.replace(/\.html$/i, '').toLowerCase()
  if (STANDALONE_PAGES.has(base) || REPLACED_PAGES.has(base)) {
    skipped.push(file)
    continue
  }

  try {
    const raw = fs.readFileSync(path.join(SRC, file), 'utf8')
    const extracted = extract(raw, file)

    const edge = toEdge(
      {
        ...extracted,
        styles: transformMarkup(extracted.styles),
        content: transformMarkup(extracted.content),
        scripts: ensureJquery(transformMarkup(extracted.scripts)),
      },
      file
    )

    const slug = slugify(file)
    fs.writeFileSync(path.join(OUT, `${slug}.edge`), edge)
    written.push(slug)
  } catch (error) {
    failed.push(`${file}: ${error.message}`)
  }
}

// A leftover include means the extraction missed a region -- surface it loudly.
const leftovers = written.filter((slug) =>
  fs.readFileSync(path.join(OUT, `${slug}.edge`), 'utf8').includes('@SPK@')
)

/**
 * Emit the slug allowlist as TypeScript so ShowcaseController can validate the
 * :page parameter against it instead of trusting user input as a view path.
 */
fs.writeFileSync(
  path.join(ROOT, 'config/showcase.ts'),
  [
    '/*',
    '|--------------------------------------------------------------------------',
    '| Showcase pages (GENERATED)',
    '|--------------------------------------------------------------------------',
    '|',
    '| Written by scripts/convert-showcase-pages.mjs. Do not edit by hand.',
    '|',
    '| These are the Imtaqin template pages rendered as reference markup at',
    '| /showcase/:page. They are not application screens -- copy the markup you',
    '| need into a real page rather than building on top of them.',
    '|',
    '*/',
    '',
    'export const showcasePages = [',
    ...written.map((slug) => `  '${slug}',`),
    '] as const',
    '',
    'export type ShowcasePage = (typeof showcasePages)[number]',
    '',
    'export const showcasePageSet: ReadonlySet<string> = new Set(showcasePages)',
    '',
    'export default showcasePages',
    '',
  ].join('\n')
)

console.log(`converted : ${written.length}`)
console.log(`skipped   : ${skipped.length} (${skipped.join(', ')})`)
if (leftovers.length) console.log(`LEFTOVER @SPK@ in: ${leftovers.join(', ')}`)
if (failed.length) {
  console.log(`FAILED    : ${failed.length}`)
  failed.forEach((f) => console.log(`  ${f}`))
}
