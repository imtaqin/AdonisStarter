/*
|--------------------------------------------------------------------------
| Agent config fan-out
|--------------------------------------------------------------------------
|
| AGENTS.md is the single source of truth for how to work in this repo. Every
| other agent-facing file is a thin pointer generated from this script, so the
| guidance can never drift between tools.
|
|   node scripts/sync-agent-configs.mjs
|   node scripts/sync-agent-configs.mjs --check   (CI: fail if out of date)
|
| Adding support for a new agent means adding one entry to AGENTS or MCP_TARGETS
| below -- not writing another markdown file by hand.
|
| Reference: https://agents.md — AGENTS.md is read natively by Codex, Cursor,
| Copilot's coding agent, Windsurf, Warp, Devin, Factory, Ona and Kimi Code.
| The rest need a pointer file or a config key, which is what this generates.
|
*/
import fs from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')
const GENERATED = 'Generated by scripts/sync-agent-configs.mjs — edit AGENTS.md instead.'

/* -------------------------------------------------------------------------- */
/* MCP servers — one definition, several config dialects                       */
/* -------------------------------------------------------------------------- */

const SERVERS = {
  'adonis-boost': {
    command: 'node',
    args: ['--import=@poppinss/ts-exec', 'mcp/boost/server.ts'],
    note: 'This project: routes, schema, components, errors, memory, git context.',
  },
  'adonis-docs': {
    command: 'npx',
    args: ['-y', 'mcp-adonis-docs'],
    note: 'Official AdonisJS/Lucid/Edge/VineJS docs. Read before writing framework code.',
  },
  'playwright': {
    command: 'npx',
    args: ['-y', '@playwright/mcp@latest', '--browser', 'chromium'],
    note: 'Drives a real browser to verify pages render.',
  },
}

const entries = () => Object.entries(SERVERS)

/** Each client wants the same servers under a slightly different shape. */
const MCP_TARGETS = [
  {
    label: 'Claude Code',
    file: '.mcp.json',
    build: () => ({
      mcpServers: Object.fromEntries(
        entries().map(([name, s]) => [
          name,
          { type: 'stdio', command: s.command, args: s.args, env: {} },
        ])
      ),
    }),
  },
  {
    label: 'Cursor',
    file: '.cursor/mcp.json',
    build: () => ({
      mcpServers: Object.fromEntries(
        entries().map(([name, s]) => [name, { command: s.command, args: s.args }])
      ),
    }),
  },
  {
    label: 'Crush',
    file: '.crush.json',
    // Crush uses `mcp`, not `mcpServers`, and can be told to treat AGENTS.md as
    // the file it writes on `/init`.
    build: () => ({
      $schema: 'https://charm.land/crush.json',
      options: { initialize_as: 'AGENTS.md' },
      mcp: Object.fromEntries(
        entries().map(([name, s]) => [name, { type: 'stdio', command: s.command, args: s.args }])
      ),
    }),
  },
  {
    label: 'Kimi Code',
    file: '.kimi-code/mcp.json',
    build: () => ({
      mcpServers: Object.fromEntries(
        entries().map(([name, s]) => [name, { command: s.command, args: s.args }])
      ),
    }),
  },
  {
    label: 'Gemini CLI',
    file: '.gemini/settings.json',
    // contextFileName makes Gemini read AGENTS.md directly, so no GEMINI.md
    // duplication is needed beyond the pointer.
    build: () => ({
      contextFileName: ['AGENTS.md', 'GEMINI.md'],
      mcpServers: Object.fromEntries(
        entries().map(([name, s]) => [name, { command: s.command, args: s.args }])
      ),
    }),
  },
  {
    label: 'VS Code / Copilot',
    file: '.vscode/mcp.json',
    build: () => ({
      servers: Object.fromEntries(
        entries().map(([name, s]) => [name, { type: 'stdio', command: s.command, args: s.args }])
      ),
    }),
  },
  {
    label: 'opencode',
    file: 'opencode.json',
    build: () => ({
      $schema: 'https://opencode.ai/config.json',
      mcp: Object.fromEntries(
        entries().map(([name, s]) => [
          name,
          { type: 'local', command: [s.command, ...s.args], enabled: true },
        ])
      ),
    }),
  },
]

/* -------------------------------------------------------------------------- */
/* Context files — pointers, never copies                                      */
/* -------------------------------------------------------------------------- */

const POINTER_BODY = (tool) =>
  [
    `# ${tool}`,
    '',
    `<!-- ${GENERATED} -->`,
    '',
    'Read **[AGENTS.md](./AGENTS.md)** — it is the single source of truth for this',
    'project and is kept deliberately short.',
    '',
    'Start with section 1, "Non-obvious rules". Four behaviours in this stack break',
    "silently if you guess at them: the generated `database/schema.ts`, Edge's",
    'camelCased component tag names, block tags inside HTML attributes, and `@each`',
    'expressions.',
    '',
    '## Tooling',
    '',
    'An MCP server called **adonis-boost** ships with this repo. Prefer its tools',
    'over reading files — they reflect what the app actually loaded:',
    '',
    '- `memory_list` / `memory_write` — decisions that outlive the session',
    '- `project_conventions` — the rules above, machine-readable',
    '- `list_routes`, `list_components`, `database_schema` — the real thing, not a guess',
    '- `last_errors` — stack traces after a 500, since you cannot see the terminal',
    '- `git_status`, `git_recent_commits`, `git_conventions` — history as context',
    '',
    'See [docs/AI-TOOLING.md](./docs/AI-TOOLING.md) for setup.',
    '',
  ].join('\n')

const CONTEXT_TARGETS = [
  { label: 'Claude Code', file: 'CLAUDE.md', body: () => POINTER_BODY('CLAUDE.md') },
  { label: 'Gemini CLI', file: 'GEMINI.md', body: () => POINTER_BODY('GEMINI.md') },
  { label: 'Crush', file: 'CRUSH.md', body: () => POINTER_BODY('CRUSH.md') },
  { label: 'Kimi Code', file: '.kimi-code/AGENTS.md', body: () => POINTER_BODY('Kimi Code') },
  { label: 'Aider', file: 'CONVENTIONS.md', body: () => POINTER_BODY('Aider conventions') },
  { label: 'Cline', file: '.clinerules', body: () => POINTER_BODY('Cline') },
  {
    label: 'GitHub Copilot',
    file: '.github/copilot-instructions.md',
    body: () => POINTER_BODY('GitHub Copilot'),
  },
  {
    label: 'Cursor',
    file: '.cursor/rules/project.mdc',
    // Cursor project rules are MDC: YAML frontmatter then markdown.
    // alwaysApply keeps it in context for every request.
    body: () =>
      [
        '---',
        'description: Project conventions for this AdonisJS dashboard',
        'alwaysApply: true',
        '---',
        '',
        POINTER_BODY('Cursor'),
      ].join('\n'),
  },
  {
    label: 'Windsurf',
    file: '.windsurf/rules/project.md',
    // Windsurf caps workspace rules at 12k characters, which a pointer is
    // nowhere near.
    body: () => ['---', 'trigger: always_on', '---', '', POINTER_BODY('Windsurf')].join('\n'),
  },
]

/* -------------------------------------------------------------------------- */

const check = process.argv.includes('--check')
const written = []
const stale = []

function emit(relative, content) {
  const target = path.join(ROOT, relative)
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null

  if (current === content) return

  if (check) {
    stale.push(relative)
    return
  }

  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, content)
  written.push(relative)
}

if (!fs.existsSync(path.join(ROOT, 'AGENTS.md'))) {
  console.error('AGENTS.md is missing — it is the source this script fans out from.')
  process.exit(1)
}

for (const target of CONTEXT_TARGETS) emit(target.file, target.body())
for (const target of MCP_TARGETS) emit(target.file, JSON.stringify(target.build(), null, 2) + '\n')

if (check) {
  if (stale.length) {
    console.error(
      `Out of date (run: node scripts/sync-agent-configs.mjs):\n  ${stale.join('\n  ')}`
    )
    process.exit(1)
  }
  console.log('All agent configs are up to date.')
} else {
  console.log(
    written.length
      ? `updated ${written.length} file(s):\n  ${written.join('\n  ')}`
      : 'already up to date'
  )
  console.log(
    `\ncontext files: ${CONTEXT_TARGETS.length}  ·  mcp configs: ${MCP_TARGETS.length}  ·  servers: ${Object.keys(SERVERS).length}`
  )
}
